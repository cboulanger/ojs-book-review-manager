import { B, browser, login, since, mails, modalForm } from './lib.mjs';
const admin = await login('admin', 'ojsadmin');
await admin.goto(`${B}/manageBookReviews/reservations`);
console.log('old URL redirects to:', admin.url().replace(B, ''));
const row = admin.locator('.ofrTable tbody tr', { hasText: 'A test book for reservations' });
await row.locator('.ofrActions a', { hasText: 'Cancel reservation' }).click();
const form = await modalForm(admin);
await form.locator('input[name=sendEmail]').uncheck();
const t = since();
await Promise.all([admin.waitForNavigation({ timeout: 20000 }), form.locator('button.submitFormButton').click()]);
console.log('rows left:', await admin.locator('.ofrTable tbody tr', { hasText: 'A test book for reservations' }).count(), '| mails to reviewer:', mails(t).filter(m => /author@/.test(m.to)).length);
await admin.goto(`${B}/manageBookReviews/assignments?status=cancelled`);
console.log('cancelled filter:', (await admin.locator('.ofrTable tbody tr').allInnerTexts()).map(x => x.replace(/\s+/g, ' ').slice(0, 100)));
const author = await login('author', 'ojsauthor');
await author.goto(`${B}/books-for-review`);
console.log('offered again:', await author.locator('.ofrReserveButton[data-object-id="6"]').count());
await browser.close();
